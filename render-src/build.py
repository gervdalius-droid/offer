"""Bundle the cabinet creator's 3D viewer into one file for the offer app: render-module.js

   python3 build.py path/to/builder/index.html  [out=render-module.js]

   From the cabinet creator (gervdalius-droid/builder, index.html) it copies, unchanged:
     the cabinet engine (DBEngine), the front view (DBFront), the assembled 3D viewer (DBAssembly)
     and the viewer's CSS (.av rules).
   Adds: adapter.js (offer cabinet → builder cabinet) and offer-3d.js (cards, live viewer).
   Run it again whenever the cabinet creator's engine or viewer changes."""
import json, os, re, sys
R = os.path.dirname(os.path.abspath(__file__))
src = open(sys.argv[1] if len(sys.argv) > 1 else os.path.join(R, '..', 'builder', 'index.html'), encoding='utf-8').read()
out_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(R, 'render-module.js')
rd = lambda f: open(os.path.join(R, f), encoding='utf-8').read()

scripts = re.findall(r'<script>(.*?)</script>', src, re.S)
def block(marker):
    hits = [s for s in scripts if marker in s[:400]]
    assert len(hits) == 1, f'{marker}: {len(hits)} script blocks'
    return hits[0]
engine = block('engine.js — Dėdės Baldai cabinet engine')
front = block('Front view of one cabinet')
asm = block('Assembly-only geometry')
anchor = 'window.DBAssembly={mount:'
assert asm.count(anchor) == 1
i = asm.index(anchor); j = asm.index('};', i) + 2
asm = asm[:j] + '\nwindow.DBAssembly.state=V;   // offer app: thumbnails are drawn from the default camera\n' + asm[j:]

# the viewer's CSS: every rule whose selector mentions .av (also inside @media)
css = re.sub(r'/\*.*?\*/', '', ''.join(re.findall(r'<style[^>]*>(.*?)</style>', src.split('<script')[0], re.S)), flags=re.S)
def match(k):
    d = 0
    for e in range(k, len(css)):
        d += css[e] == '{'; d -= css[e] == '}'
        if d == 0: return e
    return len(css) - 1
rules, i = [], 0
while True:
    j = css.find('{', i)
    if j < 0: break
    sel, e = css[i:j].strip(), match(j); body = css[j + 1:e]
    if sel.startswith('@media') or sel.startswith('@supports'):
        inner, k = [], 0
        while True:
            jj = body.find('{', k)
            if jj < 0: break
            ss, ee = body[k:jj].strip(), body.find('}', jj)
            if '.av' in ss: inner.append(ss + '{' + body[jj + 1:ee] + '}')
            k = ee + 1
        if inner: rules.append(sel + '{' + ''.join(inner) + '}')
    elif '.av' in sel and not sel.startswith('@'):
        rules.append(sel + '{' + body + '}')
    i = e + 1
av_css = '\n'.join(rules)

head = """/* =====================================================================
   Dėdės Baldai · offer app — 3D cabinet rendering from the cabinet creator
   (gervdalius-droid/builder): its engine (DBEngine), front view (DBFront)
   and assembled 3D viewer (DBAssembly) copied unchanged, plus the bridge
   from offer-app cabinets (incl. ones imported from drawings).
   Generated by render-src/build.py — do not edit by hand.
   Install: <script src="render-module.js"></script> after import-module.js
   ===================================================================== */
"""
out = ''.join([head, engine, '\n', front, '\n',
               "window.DBArt = window.DBArt || { photo: function () { return ''; } };   // connector photos: only the joint editor uses them\n",
               asm, '\n', rd('adapter.js'), '\n', rd('offer-3d.js').replace('__AV_CSS__', json.dumps(av_css))])
open(out_path, 'w', encoding='utf-8').write(out)
print(os.path.basename(out_path), len(out), 'bytes · css', len(av_css))
